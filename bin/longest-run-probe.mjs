// 最长重复段：整篇一次扫，找最长的那条「可以指着前面说」的片段。
//
// 为什么改用这个（2026-11-24，k-gram 与压缩率都被实测否决之后）：
//   k-gram 比是平均值 —— 长文本把重复稀释，夹九次「做。」在 133 字节里掉到 0.809，漏。
//   压缩覆盖率是冗余量 —— 夹九次只占 20%，从压缩角度确实不值得管，但**行为上要管**。
// 两个都不对，因为「压缩」和「退化」不是同一个量：
//   压缩问「这段能不能更短」，退化问「这个人是不是卡住了」。
// 卡住的形状是**同一个小片段连续重复很多次**，度量它只需要一个数：
//   最长的 match 有多长（LZ77 的 bestLen）。
//
// 实测（同批样本）：
//   31 行「做。」      最长 match 85
//   夹 9 个            最长 match 15
//   正常散文 / 孤立      0
// 三档分得开，而且不受文本长度稀释——它数的是「一条匹配本身」，不是占比。

import { lz77 } from "./lz77-probe.mjs";

const longest = (text) => {
  const r = lz77(text);
  let best = 0;
  for (const m of r.matches) if (m.len > best) best = m.len;
  return { len: best, count: r.matches.length, coverage: r.coverage };
};

const CASES = [
  ["31 行「做。」", Array.from({ length: 31 }, () => "做。").join("\n")],
  ["夹 9 个（加长）", ["第一步读取配置文件，确认两个门槛写在同一个文件里，并且确认它们的默认值出处。", "做。", "做。", "做。", "做。", "做。", "第二步核对台账，看最近判红的样本是不是同一份思考，还是分散在不同轮次上。", "做。", "做。", "做。", "做。", "第三步再决定要不要改阈值，改之前先问原来的值是怎么定下来的。"].join("\n")],
  ["夹 9 个（短版）", ["第一步读取配置文件。", "做。", "做。", "做。", "做。", "做。", "第二步核对台账。", "做。", "做。", "做。", "做。", "第三步再决定。"].join("\n")],
  ["变形重复", "先看台账确认最近的判红集中在同一份思考上，如果是说明计数把流式帧当成了次数。先查台账确认最近的判红都集中在同一份思考里，若是的话，说明计数把流式帧当成了次数。"],
  ["正常散文", "读完配置后我把三个阈值都记下来，然后逐条核对它们是不是写在同一个文件里。阈值分别在 defaults 与 config 两处声明，读的时候后者覆盖前者。"],
  ["长正常文（200 字，有常见短语重复）", "读完配置之后我把三个阈值都记录下来，然后逐条核对它们是不是写在同一个文件里面。阈值分别在 defaults 与 config 两处声明，读取的时候后者会覆盖前者。如果两处写得不一样，换一台机器跑出来的结果就会不同，所以判据里额外加了一条跨字段检查。写完这一段之后我又回读了一遍，确认没有把阈值写错。"],
  ["完全孤立", "甲一乙二丙三丁四戊五己六庚七辛八"],
  ["同一句 6 次（一行内）", "ok。ok。ok。ok。ok。ok。"],
];

console.log("样本".padEnd(30) + "字节".padStart(6) + "最长".padStart(6) + "匹配数".padStart(8) + "覆盖".padStart(8));
for (const [name, text] of CASES) {
  const r = longest(text);
  console.log(name.padEnd(30) + String(text.length).padStart(6) + String(r.len).padStart(6) + String(r.count).padStart(8) + r.coverage.toFixed(3).padStart(8));
}
