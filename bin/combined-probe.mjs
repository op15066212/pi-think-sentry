// 多算法联合裁决：LZ77 覆盖率 + k-gram 比，各自抓不同形状。
//
// 实测（2026-11-24）：
//   31 行「做。」       LZ 0.924  kgram 0.033   ← 连续大段，两者都抓到
//   夹 9 个（加长）      LZ 0.158  kgram ?       ← 间断重复，看 kgram
//   夹 9 个（短版）      LZ 0.389  kgram 0.519   ← 间断重复，两者都弱
//   正常散文            LZ 0.000  kgram 1.000   ← 都不抓
//
// 为什么要两个：LZ 省的是**绝对字节**，长匹配才划算（连续 30 行 = 一条 85 字节的匹配）；
// 间断的短句重复压不动，LZ 看不见。k-gram 数的是**种类**，间断也能数到，
// 但它是平均值，长文本会把重复稀释。
// 一个抓连续、一个抓间断、一个被稀释另一个不受影响——这是互补，不是叠加。
import { lz77 } from "./lz77-probe.mjs";

const kgramRatio = (text, k = 3) => {
  if (text.length < k) return 1;
  const seen = new Set();
  let total = 0;
  for (let i = 0; i + k <= text.length; i++) {
    seen.add(text.slice(i, i + k));
    total++;
  }
  return seen.size / total;
};

const CASES = [
  ["31 行「做。」", Array.from({ length: 31 }, () => "做。").join("\n")],
  ["正常散文", "读完配置后我把三个阈值都记下来，然后逐条核对它们是不是写在同一个文件里。阈值分别在 defaults 与 config 两处声明，读的时候后者覆盖前者。"],
  ["夹 9 个（加长）", ["第一步读取配置文件，确认两个门槛写在同一个文件里，并且确认它们的默认值出处。", "做。", "做。", "做。", "做。", "做。", "第二步核对台账，看最近判红的样本是不是同一份思考，还是分散在不同轮次上。", "做。", "做。", "做。", "做。", "第三步再决定要不要改阈值，改之前先问原来的值是怎么定下来的。"].join("\n")],
  ["夹 9 个（短版）", ["第一步读取配置文件。", "做。", "做。", "做。", "做。", "做。", "第二步核对台账。", "做。", "做。", "做。", "做。", "第三步再决定。"].join("\n")],
  ["变形重复", "先看台账确认最近的判红集中在同一份思考上，如果是说明计数把流式帧当成了次数。先查台账确认最近的判红都集中在同一份思考里，若是的话，说明计数把流式帧当成了次数。"],
  ["完全孤立", "甲一乙二丙三丁四戊五己六庚七辛八"],
  ["长正常文（200 字）", "读完配置之后我把三个阈值都记录下来，然后逐条核对它们是不是写在同一个文件里面。阈值分别在 defaults 与 config 两处声明，读取的时候后者会覆盖前者。如果两处写得不一样，换一台机器跑出来的结果就会不同，所以判据里额外加了一条跨字段检查。"],
];

console.log("样本".padEnd(22) + "字节".padStart(6) + "LZ".padStart(8) + "kgram".padStart(8) + "  联合");
for (const [name, text] of CASES) {
  const lz = lz77(text).coverage;
  const kg = kgramRatio(text, 3);
  // 联合：LZ 抓连续（0.5 以上），kgram 抓间断（0.5 以下）
  const verdict = lz >= 0.5 ? "红(LZ)" : kg <= 0.5 ? "红(kg)" : "绿";
  console.log(
    name.padEnd(22) + String(text.length).padStart(6) + lz.toFixed(3).padStart(8) + kg.toFixed(3).padStart(8) + "  " + verdict,
  );
}
